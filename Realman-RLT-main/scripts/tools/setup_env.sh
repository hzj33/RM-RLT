#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'EOF'
One-click environment setup for Realman-RLT.

Usage:
  bash scripts/tools/setup_env.sh [options]

Options:
  --env-name NAME        Conda env name. Default: lerobot
  --python VERSION      Python version. Default: 3.10
  --cuda cu118|cpu|skip PyTorch build. Default: cu118
  --rm-api-path PATH    Optional RealMan RM_API2/Python path to save in .env.local
  --quest-smoke-test    Run the interactive Quest -> RealMan motion test after setup
  --arm-ip IP           Required with --quest-smoke-test
  --arm-port PORT       RealMan port for --quest-smoke-test. Default: 8080
  --no-check            Do not run environment check after install
  -h, --help            Show this help

Examples:
  bash scripts/tools/setup_env.sh

  bash scripts/tools/setup_env.sh --rm-api-path PATH

  bash scripts/tools/setup_env.sh --quest-smoke-test --arm-ip <RM65-IP>

Notes:
  - RealMan SDK and Quest/XRoboToolkit are external dependencies. This script
    does not download or install them. See ENV_SETUP_CN.md.
  - If you already have a working env named lerobot, the script reuses it.
EOF
}

ENV_NAME="lerobot"
PYTHON_VERSION="3.10"
CUDA_BUILD="cu118"
RM_API_PATH_VALUE=""
RUN_CHECK=1
QUEST_SMOKE_TEST=0
ARM_IP_VALUE=""
ARM_PORT_VALUE="8080"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --env-name)
      ENV_NAME="${2:?missing value for --env-name}"
      shift 2
      ;;
    --python)
      PYTHON_VERSION="${2:?missing value for --python}"
      shift 2
      ;;
    --cuda)
      CUDA_BUILD="${2:?missing value for --cuda}"
      shift 2
      ;;
    --rm-api-path)
      RM_API_PATH_VALUE="${2:?missing value for --rm-api-path}"
      shift 2
      ;;
    --quest-smoke-test)
      QUEST_SMOKE_TEST=1
      shift
      ;;
    --arm-ip)
      ARM_IP_VALUE="${2:?missing value for --arm-ip}"
      shift 2
      ;;
    --arm-port)
      ARM_PORT_VALUE="${2:?missing value for --arm-port}"
      shift 2
      ;;
    --no-check)
      RUN_CHECK=0
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "[setup] unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if [[ "$QUEST_SMOKE_TEST" -eq 1 && -z "$ARM_IP_VALUE" ]]; then
  echo "[setup] --arm-ip is required with --quest-smoke-test." >&2
  exit 2
fi

if [[ "$QUEST_SMOKE_TEST" -eq 1 && "$RUN_CHECK" -eq 0 ]]; then
  echo "[setup] --quest-smoke-test requires the environment check; do not use --no-check." >&2
  exit 2
fi

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/../.." && pwd)"
REQ_FILE="$REPO_ROOT/requirements/realman-rlt.txt"
LOCAL_ENV="$REPO_ROOT/.env.local"
THIRD_PARTY_DIR="$REPO_ROOT/third_party"
TOTAL_STEPS=7
if [[ "$RUN_CHECK" -eq 1 ]]; then
  TOTAL_STEPS=8
fi
if [[ "$QUEST_SMOKE_TEST" -eq 1 ]]; then
  TOTAL_STEPS=$((TOTAL_STEPS + 1))
fi
CURRENT_STEP=0

step() {
  CURRENT_STEP=$((CURRENT_STEP + 1))
  printf '\n[setup %d/%d] %s\n' "$CURRENT_STEP" "$TOTAL_STEPS" "$1"
}

write_local_env() {
  local tmp
  tmp="$(mktemp "${LOCAL_ENV}.XXXXXX")"

  {
    echo '# >>> Realman-RLT setup_env.sh managed block >>>'
    echo '# Generated by setup_env.sh. Add user settings outside this block.'
    echo "export REALMAN_RLT_ROOT=\"$REPO_ROOT\""
    echo 'export THIRD_PARTY_DIR="${THIRD_PARTY_DIR:-$REALMAN_RLT_ROOT/third_party}"'
    echo 'export HF_HOME="$REALMAN_RLT_ROOT/.cache/huggingface"'
    echo 'export HF_DATASETS_CACHE="$HF_HOME/datasets"'
    if [[ -n "$RM_API_PATH_VALUE" ]]; then
      echo "export RM_API2_PYTHON_PATH=\"$RM_API_PATH_VALUE\""
      echo 'export RM_API_PATH="$RM_API2_PYTHON_PATH"'
    fi
    echo '# <<< Realman-RLT setup_env.sh managed block <<<'
    if [[ -f "$LOCAL_ENV" ]]; then
      printf '\n'
      sed '/^# >>> Realman-RLT setup_env.sh managed block >>>$/,/^# <<< Realman-RLT setup_env.sh managed block <<<$/d' \
        "$LOCAL_ENV"
    fi
  } > "$tmp"
  mv "$tmp" "$LOCAL_ENV"
}

step "checking prerequisites"
if ! command -v conda >/dev/null 2>&1; then
  echo "[setup] conda not found. Install Miniconda/Anaconda first." >&2
  exit 1
fi

if [[ ! -f "$REQ_FILE" ]]; then
  echo "[setup] missing requirements file: $REQ_FILE" >&2
  exit 1
fi

if [[ -n "$RM_API_PATH_VALUE" && ! -d "$RM_API_PATH_VALUE" ]]; then
  echo "[setup] --rm-api-path does not exist or is not a directory: $RM_API_PATH_VALUE" >&2
  exit 2
fi

echo "[setup] repo: $REPO_ROOT"
echo "[setup] env:  $ENV_NAME"

step "creating or reusing Conda environment '$ENV_NAME'"
if conda env list | awk '{print $1}' | grep -Fxq "$ENV_NAME"; then
  echo "[setup] conda env '$ENV_NAME' already exists; reuse it."
else
  echo "[setup] creating conda env '$ENV_NAME' with python=$PYTHON_VERSION"
  conda create -y -n "$ENV_NAME" "python=$PYTHON_VERSION"
fi

run_in_env() {
  conda run --no-capture-output -n "$ENV_NAME" "$@"
}

step "upgrading pip tooling"
run_in_env python -m pip install --progress-bar on --upgrade pip setuptools wheel

step "installing PyTorch ($CUDA_BUILD)"
case "$CUDA_BUILD" in
  cu118)
    run_in_env python -m pip install \
      --progress-bar on \
      "torch==2.7.1+cu118" "torchvision==0.22.1+cu118" \
      --index-url https://download.pytorch.org/whl/cu118
    ;;
  cpu)
    run_in_env python -m pip install --progress-bar on torch torchvision --index-url https://download.pytorch.org/whl/cpu
    ;;
  skip)
    echo "[setup] PyTorch install skipped by --cuda skip"
    ;;
  *)
    echo "[setup] unsupported --cuda '$CUDA_BUILD'. Use cu118, cpu, or skip." >&2
    exit 2
    ;;
esac

step "installing project Python dependencies"
run_in_env python -m pip install --progress-bar on -r "$REQ_FILE"

step "ensuring GUI OpenCV is used"
run_in_env python -m pip uninstall -y opencv-python-headless >/dev/null 2>&1 || true
# OpenCV GUI and headless wheels share cv2 files. Reinstall the GUI wheel after
# removing headless so pip cannot leave a partial cv2 package behind.
run_in_env python -m pip install --progress-bar on --force-reinstall --no-deps "opencv-python==4.12.0.88"

step "creating project directories and updating .env.local"
mkdir -p "$REPO_ROOT/.cache/huggingface"
mkdir -p "$THIRD_PARTY_DIR"
write_local_env
echo "[setup] wrote local env file: $LOCAL_ENV"

if [[ "$RUN_CHECK" -eq 1 ]]; then
  step "running environment check"
  if [[ -n "$RM_API_PATH_VALUE" ]]; then
    run_in_env python "$REPO_ROOT/scripts/tools/check_env.py" --rm-api-path "$RM_API_PATH_VALUE"
  else
    run_in_env python "$REPO_ROOT/scripts/tools/check_env.py" --skip-hardware
  fi
fi

if [[ "$QUEST_SMOKE_TEST" -eq 1 ]]; then
  step "running Quest -> RealMan interactive motion test"
  TEST_SCRIPT="$REPO_ROOT/scripts/tools/test_quest_realman.py"
  TEST_ARGS=(python "$TEST_SCRIPT" --arm-ip "$ARM_IP_VALUE" --arm-port "$ARM_PORT_VALUE")
  if [[ -n "$RM_API_PATH_VALUE" ]]; then
    TEST_ARGS+=(--rm-api-path "$RM_API_PATH_VALUE")
  fi
  echo "[setup] This test moves the real robot. Confirm the terminal safety prompts before motion is enabled."
  run_in_env bash -c 'source "$1"; shift; exec "$@"' bash "$LOCAL_ENV" "${TEST_ARGS[@]}"
fi

cat <<EOF

[setup] done.

Activate the environment:
  conda activate $ENV_NAME

Load local environment variables when needed:
  source .env.local

Quick check:
  python scripts/tools/check_env.py --skip-hardware
EOF
